_lang = "ru"


def set_lang(lang: str) -> str:
    global _lang
    key = (lang or "ru").lower()
    if key not in _STRINGS:
        key = "ru"
    _lang = key
    return _lang


def lang() -> str:
    return _lang


def t(key: str) -> str:
    pack = _STRINGS.get(_lang) or _STRINGS["ru"]
    if key in pack:
        return pack[key]
    return _STRINGS["en"].get(key, key)
